decoded = []
for target, sha, payload in FILES:
    data = base64.b64decode("".join(payload.split()))
    if hashlib.sha256(data).hexdigest() != sha:
        sys.exit(f"Checksum mismatch for {target}: damaged in transit. Nothing was changed.")
    decoded.append((ROOT / target, data))
(ROOT / "coinbot").mkdir(exist_ok=True)
backups = []
for path, data in decoded:
    if path.exists():
        backup = path.with_name(path.name + ".bak_before_coinbot")
        if not backup.exists():
            shutil.copy2(path, backup)
            backups.append(str(backup))
    path.write_bytes(data)
    if path.suffix == ".py":
        try:
            py_compile.compile(str(path), doraise=True)
        except py_compile.PyCompileError as exc:
            sys.exit(f"{path} did not compile ({exc}). Restore from the .bak file if one was listed.")
    print("installed", path)
