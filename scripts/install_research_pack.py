decoded = []
for target, sha, payload in FILES:
    data = base64.b64decode("".join(payload.split()))
    if hashlib.sha256(data).hexdigest() != sha:
        sys.exit(f"Checksum mismatch for {target}: damaged in transit. Nothing was changed.")
    decoded.append((ROOT / target, data))
if not ROOT.exists():
    sys.exit(f"{ROOT} not found. Nothing was changed.")

backups = []
for path, data in decoded:
    if path.exists():
        backup = path.with_name(path.name + ".bak_before_research_pack")
        shutil.copy2(path, backup)
        backups.append(str(backup))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(data)
    py_compile.compile(str(path), doraise=True)
    print("installed", path)

check = subprocess.run([sys.executable, str(ROOT / "scripts/daily_scorecard.py"), "--repo-root", str(ROOT)], capture_output=True, text=True)
print("--- scorecard preview ---")
print((check.stdout + check.stderr).strip())
print("-------------------------")
if check.returncode != 0:
    sys.exit("Scorecard preview failed; files are installed but the daily job was NOT scheduled.")

if shutil.which("pm2"):
    subprocess.run(["pm2", "delete", "netzara-scorecard"], capture_output=True)
    job = subprocess.run(
        ["pm2", "start", str(ROOT / "scripts/daily_scorecard.py"), "--name", "netzara-scorecard", "--interpreter", "python3",
         "--cron-restart", "0 7 * * *", "--no-autorestart", "--", "--repo-root", str(ROOT), "--send"],
        capture_output=True, text=True)
    subprocess.run(["pm2", "save"], capture_output=True)
    print("pm2 job netzara-scorecard:", "scheduled 07:00 UTC (08:00 Lagos)" if job.returncode == 0 else "FAILED: " + job.stderr[-300:])
else:
    print("pm2 not found; the daily job was not scheduled.")
print("Applied. Backups:", backups or "none needed (new files)")
